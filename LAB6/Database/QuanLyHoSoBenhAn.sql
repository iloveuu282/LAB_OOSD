CREATE TABLE BenhNhan(BenhNhanID INT IDENTITY PRIMARY KEY, HoTen NVARCHAR(120) NOT NULL, NgaySinh DATE, DiaChi NVARCHAR(250), DienThoai VARCHAR(20), Anh3x4 NVARCHAR(300));
CREATE TABLE Khoa(KhoaID INT IDENTITY PRIMARY KEY, TenKhoa NVARCHAR(120) NOT NULL UNIQUE);
CREATE TABLE BacSi(BacSiID INT IDENTITY PRIMARY KEY, HoTen NVARCHAR(120) NOT NULL, KhoaID INT NOT NULL REFERENCES Khoa(KhoaID));
CREATE TABLE LePhiNam(LePhiID INT IDENTITY PRIMARY KEY, BenhNhanID INT NOT NULL REFERENCES BenhNhan(BenhNhanID), Nam INT NOT NULL CHECK(Nam BETWEEN 2000 AND 2100), SoTien DECIMAL(18,2) NOT NULL CHECK(SoTien>=0), NgayDong DATETIME2 NOT NULL DEFAULT SYSDATETIME(), TrangThai VARCHAR(20) NOT NULL CHECK(TrangThai IN ('DA_DONG','HOAN_TIEN')), CONSTRAINT UQ_LePhiNam UNIQUE(BenhNhanID,Nam));
CREATE TABLE HoSoBenhAn(HoSoID INT IDENTITY PRIMARY KEY, MaHoSo VARCHAR(30) NOT NULL UNIQUE, BenhNhanID INT NOT NULL UNIQUE REFERENCES BenhNhan(BenhNhanID), NgayCap DATETIME2 NOT NULL DEFAULT SYSDATETIME());
CREATE TABLE PhieuKham(PhieuKhamID INT IDENTITY PRIMARY KEY, HoSoID INT NOT NULL REFERENCES HoSoBenhAn(HoSoID), BacSiID INT NOT NULL REFERENCES BacSi(BacSiID), NgayGio DATETIME2 NOT NULL DEFAULT SYSDATETIME(), TrieuChung NVARCHAR(1000), HuyetAp NVARCHAR(30), ThanNhiet DECIMAL(4,1), LoaiKham VARCHAR(20) NOT NULL CHECK(LoaiKham IN ('THUONG','DINH_KY')), TrangThai VARCHAR(30) NOT NULL DEFAULT 'DANG_KHAM' CHECK(TrangThai IN ('DANG_KHAM','CHO_THANH_TOAN','HOAN_TAT')));
CREATE TABLE XetNghiem(XetNghiemID INT IDENTITY PRIMARY KEY, PhieuKhamID INT NOT NULL REFERENCES PhieuKham(PhieuKhamID), TenXetNghiem NVARCHAR(150) NOT NULL, KetQua NVARCHAR(2000), TrangThai VARCHAR(20) NOT NULL DEFAULT 'CHI_DINH');
CREATE TABLE ToaThuoc(ToaThuocID INT IDENTITY PRIMARY KEY, PhieuKhamID INT NOT NULL UNIQUE REFERENCES PhieuKham(PhieuKhamID), NgayKe DATETIME2 NOT NULL DEFAULT SYSDATETIME(), LoiDan NVARCHAR(1000));
CREATE TABLE Thuoc(ThuocID INT IDENTITY PRIMARY KEY, TenThuoc NVARCHAR(150) NOT NULL, DonVi NVARCHAR(40));
CREATE TABLE ChiTietToa(ToaThuocID INT NOT NULL REFERENCES ToaThuoc(ToaThuocID), ThuocID INT NOT NULL REFERENCES Thuoc(ThuocID), SoLuong INT NOT NULL CHECK(SoLuong>0), LieuDung NVARCHAR(300) NOT NULL, PRIMARY KEY(ToaThuocID,ThuocID));
CREATE TABLE LichKham(LichKhamID INT IDENTITY PRIMARY KEY, HoSoID INT NOT NULL REFERENCES HoSoBenhAn(HoSoID), NgayHen DATETIME2 NOT NULL, Quy AS (DATEPART(QUARTER,NgayHen)) PERSISTED, Nam AS (DATEPART(YEAR,NgayHen)) PERSISTED, TrangThai VARCHAR(20) NOT NULL DEFAULT 'DA_HEN', CONSTRAINT UQ_LichKhamQuy UNIQUE(HoSoID,Nam,Quy));
CREATE TABLE ThanhToan(ThanhToanID INT IDENTITY PRIMARY KEY, PhieuKhamID INT NOT NULL UNIQUE REFERENCES PhieuKham(PhieuKhamID), SoTien DECIMAL(18,2) NOT NULL CHECK(SoTien>=0), NgayThanhToan DATETIME2 NOT NULL DEFAULT SYSDATETIME(), TrangThai VARCHAR(20) NOT NULL CHECK(TrangThai IN ('DA_THANH_TOAN','HOAN_TIEN')));
GO
CREATE OR ALTER PROCEDURE dbo.sp_DangKyLanDau @HoTen NVARCHAR(120), @NgaySinh DATE, @DiaChi NVARCHAR(250), @DienThoai VARCHAR(20), @Nam INT, @LePhi DECIMAL(18,2), @MaHoSo VARCHAR(30)
AS BEGIN SET NOCOUNT ON; SET XACT_ABORT ON;
BEGIN TRY BEGIN TRAN;
DECLARE @ID INT;
INSERT BenhNhan(HoTen,NgaySinh,DiaChi,DienThoai) VALUES(@HoTen,@NgaySinh,@DiaChi,@DienThoai);
SET @ID=SCOPE_IDENTITY();
INSERT LePhiNam(BenhNhanID,Nam,SoTien,TrangThai) VALUES(@ID,@Nam,@LePhi,'DA_DONG');
INSERT HoSoBenhAn(MaHoSo,BenhNhanID) VALUES(@MaHoSo,@ID);
COMMIT; SELECT @ID AS BenhNhanID;
END TRY BEGIN CATCH IF @@TRANCOUNT>0 ROLLBACK; THROW; END CATCH END;
GO
CREATE TYPE dbo.DongThuoc AS TABLE(ThuocID INT PRIMARY KEY,SoLuong INT NOT NULL,LieuDung NVARCHAR(300) NOT NULL);
GO
CREATE OR ALTER PROCEDURE dbo.sp_LapToa @PhieuKhamID INT,@LoiDan NVARCHAR(1000),@DsThuoc dbo.DongThuoc READONLY
AS BEGIN SET NOCOUNT ON; SET XACT_ABORT ON;
BEGIN TRY BEGIN TRAN;
IF NOT EXISTS(SELECT 1 FROM PhieuKham WITH(UPDLOCK,HOLDLOCK) WHERE PhieuKhamID=@PhieuKhamID AND TrangThai <> 'HOAN_TAT') THROW 50001,N'Phiếu khám không hợp lệ',1;
IF NOT EXISTS(SELECT 1 FROM @DsThuoc) OR EXISTS(SELECT 1 FROM @DsThuoc WHERE SoLuong<=0) THROW 50002,N'Danh sách thuốc không hợp lệ',1;
INSERT ToaThuoc(PhieuKhamID,LoiDan) VALUES(@PhieuKhamID,@LoiDan);
DECLARE @ToaID INT=SCOPE_IDENTITY();
INSERT ChiTietToa(ToaThuocID,ThuocID,SoLuong,LieuDung) SELECT @ToaID,ThuocID,SoLuong,LieuDung FROM @DsThuoc;
COMMIT; SELECT @ToaID AS ToaThuocID;
END TRY BEGIN CATCH IF @@TRANCOUNT>0 ROLLBACK; THROW; END CATCH END;
GO
CREATE OR ALTER PROCEDURE dbo.sp_HoanTatDieuTri @PhieuKhamID INT
AS BEGIN SET NOCOUNT ON; SET XACT_ABORT ON;
BEGIN TRY BEGIN TRAN;
IF NOT EXISTS(SELECT 1 FROM ThanhToan WITH(UPDLOCK,HOLDLOCK) WHERE PhieuKhamID=@PhieuKhamID AND TrangThai='DA_THANH_TOAN') THROW 50003,N'Chưa thanh toán viện phí',1;
UPDATE PhieuKham SET TrangThai='HOAN_TAT' WHERE PhieuKhamID=@PhieuKhamID AND TrangThai<>'HOAN_TAT';
IF @@ROWCOUNT=0 THROW 50004,N'Phiếu khám không hợp lệ hoặc đã hoàn tất',1;
COMMIT;
END TRY BEGIN CATCH IF @@TRANCOUNT>0 ROLLBACK; THROW; END CATCH END;
GO
